import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

DATA = "data"   # папка с исходными файлами

# ======================================================================
# Блок 1. Загрузка и первичный осмотр
# ======================================================================
# ВНИМАНИЕ: orders.csv — разделитель ';', десятичная запятая, кодировка utf-8-sig
orders    = pd.read_csv(f"{DATA}/orders.csv", sep=";", decimal=",", encoding="utf-8-sig")
customers = pd.read_csv(f"{DATA}/customers.csv", encoding="utf-8-sig")
returns   = pd.read_csv(f"{DATA}/returns.csv",   encoding="utf-8-sig")
products  = pd.read_excel(f"{DATA}/products.xlsx", sheet_name="Товары")

print("orders:", orders.shape, "| customers:", customers.shape,
      "| returns:", returns.shape, "| products:", products.shape)
for name, df in [("orders", orders),
                 ("customers", customers),
                 ("returns", returns),
                 ("products", products),]:
    print(f"\n----- {name} -----")
    print("shape:", df.shape)
    print(df.head())
    print("\ntypes:")
    print(df.dtypes)


# ======================================================================
# Блок 2. Очистка данных
# ======================================================================
orders["Дата"] = pd.to_datetime(
    orders["Дата"], format="mixed", dayfirst=True, errors="coerce"
)
print("\n2.1 Дата заказов -> datetime")
print(orders["Дата"].dtype)
print("Не распознано (NaT):", orders["Дата"].isna().sum())

# ----------------------------------------------------------------------
# TODO 2.2: полные дубликаты в orders и customers
# ----------------------------------------------------------------------
before_orders = len(orders)
orders = orders.drop_duplicates()
removed_orders = before_orders - len(orders)

before_customers = len(customers)
customers = customers.drop_duplicates()
removed_customers = before_customers - len(customers)

print("\n2.2 Дубликаты")
print(f"orders:    удалено {removed_orders} строк, осталось {len(orders)}")
print(f"customers: удалено {removed_customers} строк, осталось {len(customers)}")

# ----------------------------------------------------------------------
# TODO 2.3: убрать строки с Количество <= 0
# ----------------------------------------------------------------------
before_qty = len(orders)
orders = orders[orders["Количество"] > 0]
removed_qty = before_qty - len(orders)
print("\n2.3 Ошибочные количества (<= 0)")
print(f"удалено {removed_qty} строк, осталось {len(orders)}")

# ----------------------------------------------------------------------
# TODO 2.4: пропуски Скидка_процент -> 0; Пол -> "Не указан"
# ----------------------------------------------------------------------
orders["Скидка_процент"] = orders["Скидка_процент"].fillna(0)
customers["Пол"] = customers["Пол"].fillna("Не указан")

print("\n2.4 Пропуски заполнены")
print("orders['Скидка_процент'] NaN:", orders["Скидка_процент"].isna().sum())
print("customers['Пол'] NaN:", customers["Пол"].isna().sum())

# ----------------------------------------------------------------------
# TODO 2.5: нормализовать Город
# ----------------------------------------------------------------------
customers["Город"] = customers["Город"].str.strip().str.title()

print("\n2.5 Город нормализован")
print("Уникальных городов:", customers["Город"].nunique())
print(customers["Город"].value_counts().head())

# ----------------------------------------------------------------------
# TODO 2.6: Бренд -> strip(); Себестоимость -> медиана по категории
# ----------------------------------------------------------------------
products["Бренд"] = products["Бренд"].str.strip()

products["Себестоимость"] = products.groupby("Категория")["Себестоимость"] \
    .transform(lambda s: s.fillna(s.median()))

print("\n2.6 products очищен")
print("Бренд -> strip(): готово")
print("Себестоимость NaN после заполнения:", products["Себестоимость"].isna().sum())



# ======================================================================
orders["Выручка"] = (
    orders["Количество"] * orders["Цена"] * (1 - orders["Скидка_процент"] / 100)
)

print("\n3.1 Выручка посчитана")
print("Суммарная выручка:", round(orders["Выручка"].sum(), 2))
print(orders[["order_id", "Количество", "Цена", "Скидка_процент", "Выручка"]].head())

# ----------------------------------------------------------------------
# TODO 3.2: Прибыль = Выручка - Себестоимость_позиции
# ----------------------------------------------------------------------
orders = orders.merge(
    products[["product_id", "Себестоимость"]],
    on="product_id",
    how="left",
)
orders["Себестоимость_позиции"] = orders["Себестоимость"] * orders["Количество"]
orders["Прибыль"] = orders["Выручка"] - orders["Себестоимость_позиции"]

print("\n3.2 Прибыль посчитана")
print("Суммарная прибыль:", round(orders["Прибыль"].sum(), 2))
print(orders[["order_id", "Выручка", "Себестоимость_позиции", "Прибыль"]].head())

# ----------------------------------------------------------------------
# TODO 3.3: Год и Месяц из даты
# ----------------------------------------------------------------------
orders["Год"] = orders["Дата"].dt.year
orders["Месяц"] = orders["Дата"].dt.to_period("M")

print("\n3.3 Год и Месяц добавлены")
print(orders[["Дата", "Год", "Месяц"]].head())

# ----------------------------------------------------------------------
# TODO 3.4: онлайн-заказы со скидкой -> топ-10 по выручке
# ----------------------------------------------------------------------
online_disc = orders[(orders["Канал"] == "Онлайн") & (orders["Скидка_процент"] > 0)]
top10_online_disc = (
    online_disc.sort_values("Выручка", ascending=False).head(10)
)

print("\n3.4 Топ-10 онлайн-заказов со скидкой по выручке")
print(
    top10_online_disc[
        ["order_id", "Дата", "product_id", "Количество",
         "Цена", "Скидка_процент", "Выручка"]
    ].to_string(index=False)
)

